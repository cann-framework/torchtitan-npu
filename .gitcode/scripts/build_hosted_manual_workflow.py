"""Generate a thin personal workflow that bootstraps the pinned Lite Actions SDK."""

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / ".gitcode/workflow-templates/manual_sdk_bootstrap.py"
OUTPUT = ROOT / ".gitcode/workflows/torchtitan_forward_manual.yml"

# Updated only from a reviewed immutable SDK Git object.
SDK_SHA = "3ec10e5560f8c81f6c718cd0febb8855f8bc9647"
BUNDLE_SHA256 = "bd27f337638cd52a85b7474c159d7da4333602e23365aee12a481ae5c77f0577"
RAW_SHA256 = "902da91808b5a39125276045ad0fc744444ffc7b0c7a9a0f9e89a72efe0475f7"
BUNDLE = ROOT / ".gitcode/workflow-templates/manual_sdk_bundle.b64"
SDK_FILES = (
    "ci_core/__init__.py",
    "ci_core/gitcode_manual/__init__.py",
    "ci_core/gitcode_manual/aggregate.py",
    "ci_core/gitcode_manual/capture.py",
    "ci_core/gitcode_manual/cli.py",
    "ci_core/gitcode_manual/common.py",
    "ci_core/gitcode_manual/dispatch.py",
)


def scripts():
    import base64

    encoded = BUNDLE.read_text(encoding="ascii").strip()
    compressed = base64.b64decode(encoded, validate=True)
    if len(compressed) > 40 * 1024 or hashlib.sha256(compressed).hexdigest() != BUNDLE_SHA256:
        raise ValueError("SDK_BUNDLE_DIGEST_MISMATCH")
    source = TEMPLATE.read_text()
    values = {
        "__SDK_SHA__": SDK_SHA,
        "__BUNDLE_SHA256__": BUNDLE_SHA256,
        "__RAW_SHA256__": RAW_SHA256,
        "__EXPECTED_FILES__": repr(SDK_FILES),
        "__BUNDLE_B64__": repr(encoded),
    }
    for key, value in values.items():
        if source.count(key) != 1:
            raise ValueError("SDK_BOOTSTRAP_PIN_PLACEHOLDER_INVALID")
        source = source.replace(key, value)
    command = "python3 -I -B - <<'PY'\n" + source.rstrip("\n") + "\nPY\n"
    if len(command.encode()) >= 64000:
        raise ValueError("SDK_BOOTSTRAP_SCRIPT_TOO_LARGE")
    return command, hashlib.sha256(command.encode()).hexdigest()


def _step(script, *, step_id, step_name, environment):
    lines = [
        "          - id: " + step_id,
        "            name: " + step_name,
        "            shell: bash",
        "            working-directory: '.'",
        "            env:",
    ]
    for key, value in environment.items():
        lines.append("              " + key + ": " + value)
    lines.append("            run: |")
    lines.extend("              " + line if line else "" for line in script.splitlines())
    return "\n".join(lines) + "\n"


def render():
    script, capture_script_sha256 = scripts()
    d = chr(36)
    header = """# Generated by .gitcode/scripts/build_hosted_manual_workflow.py.
# Business logic is the embedded Lite Actions SDK subset pinned to its reviewed commit.
# Manual current-observation only, NOT original PR provenance or official CANN acceptance.
name: TorchTitan Personal Manual Forward
on:
  workflow_dispatch:
    inputs:
      pr_number:
        description: Open personal-repository PR number
        type: number
        required: true
      test_case:
        description: worker_os_blue selects OS; os_8p selects OS and 8P; os_8p_16p selects all three cases
        type: choice
        options: [worker_os_blue, os_8p, os_8p_16p]
        default: worker_os_blue
permissions:
  action: read
  repository: read
  pr: read
  project: read
  issue: none
  note: none
stages:
  manual:
    name: Manual personal prevalidation
    jobs:
"""
    base = {
        "EVENT_NAME": "${{ atomgit.event_name }}",
        "RUN_ATTEMPT": "${{ atomgit.run_attempt }}",
        "REPOSITORY": "${{ atomgit.repository }}",
        "REPOSITORY_ID": "${{ atomgit.repository_id }}",
        "REF": "${{ atomgit.ref }}",
        "ACTOR": "${{ atomgit.actor }}",
        "CONTROL_SHA": "${{ atomgit.sha }}",
        "ATOMGIT_TOKEN": "${{ atomgit.token }}",
    }
    jobs = [
        (
            "manual_capture",
            "Capture manual request",
            None,
            {
                **base,
                "PR_NUMBER": "${{ inputs.pr_number }}",
                "TEST_CASE": "${{ inputs.test_case }}",
                "LITE_GITCODE_MANUAL_PHASE": "capture",
            },
        ),
        (
            "manual_forward",
            "Dispatch and wait exact GitHub run",
            ["manual_capture"],
            {
                **base,
                "LITE_ACTIONS_GITHUB_TOKEN": "${{ secrets.LITE_ACTIONS_GITHUB_TOKEN }}",
                "LITE_GITCODE_CAPTURE_SCRIPT_SHA256": capture_script_sha256,
                "LITE_GITCODE_MANUAL_PHASE": "forward",
            },
        ),
    ]
    for key, name, needs, environment in jobs:
        header += "      " + key + ":\n        name: " + key + "\n"
        header += (
            "        if: ${{ atomgit.repository == 'depeng1994/torchtitan-npu' && "
            "atomgit.event_name == 'Manual' && atomgit.ref == 'refs/heads/master' }}\n"
        )
        if needs:
            header += "        needs: [" + ", ".join(needs) + "]\n"
        if key == "manual_forward":
            header += (
                "        outputs:\n"
                "          case_os_result: " + d + "{{ steps.manual_forward.outputs.case_os_result }}\n"
                "          case_8p_result: " + d + "{{ steps.manual_forward.outputs.case_8p_result }}\n"
                "          case_16p_result: " + d + "{{ steps.manual_forward.outputs.case_16p_result }}\n"
                "          forward_gate: " + d + "{{ steps.manual_forward.outputs.forward_gate }}\n"
                "          forward_gate_reason: " + d + "{{ steps.manual_forward.outputs.forward_gate_reason }}\n"
            )
        header += "        runs-on: [ubuntu-latest, x64, small]\n        timeout-minutes: 20\n        steps:\n"
        header += _step(
            script,
            # The GitCode platform metadata exposes this user's step identifier as "1".
            # Keep the job identifier (manual_capture) separate from the step identifier.
            step_id=("1" if key == "manual_capture" else key),
            step_name=("Capture manual request" if key == "manual_capture" else "Dispatch and wait exact GitHub run"),
            environment=environment,
        )

    for case_id, job_name, label, output_name in (
        ("worker_os_blue", "case_os_result", "OS result", "case_os_result"),
        ("dispatch_smoke_8p", "case_8p_result", "8P result", "case_8p_result"),
        ("dispatch_smoke_16p", "case_16p_result", "16P result", "case_16p_result"),
    ):
        header += (
            "      " + job_name + ":\n"
            "        name: " + label + "\n"
            "        if: ${{ always() && atomgit.repository == 'depeng1994/torchtitan-npu' && "
            "atomgit.event_name == 'Manual' && atomgit.ref == 'refs/heads/master' }}\n"
            "        needs: [manual_capture, manual_forward]\n"
            "        runs-on: [ubuntu-latest, x64, small]\n"
            "        timeout-minutes: 5\n"
            "        steps:\n"
        )
        environment = {
            "RESULT_CASE": case_id,
            "CASE_EVIDENCE": "${{ needs.manual_forward.outputs." + output_name + " }}",
            "CAPTURE_RESULT": "${{ needs.manual_capture.result }}",
            "CAPTURE_ATTEMPT": "${{ atomgit.run_attempt }}",
            "CONTROL_SHA": "${{ atomgit.sha }}",
            "LITE_GITCODE_MANUAL_PHASE": "result",
        }
        # Capture binds the platform's native run ID, not the unsupported context expression.
        result_script = 'export CAPTURE_RUN_ID="${ATOMGIT_RUN_ID:?ATOMGIT_RUN_ID_REQUIRED}"\n' + script
        header += _step(
            result_script,
            step_id="display_" + case_id,
            step_name=label,
            environment=environment,
        )

    header += (
        "      aggregate_gate:\n"
        "        name: Aggregate Forward and authority gate\n"
        "        if: " + d + "{{ always() && atomgit.repository == 'depeng1994/torchtitan-npu' && "
        "atomgit.event_name == 'Manual' && atomgit.ref == 'refs/heads/master' }}\n"
        "        needs: [manual_capture, manual_forward, case_os_result, case_8p_result, case_16p_result]\n"
        "        runs-on: [ubuntu-latest, x64, small]\n"
        "        timeout-minutes: 2\n"
        "        steps:\n"
    )
    aggregate_environment = {
        "CAPTURE_RESULT": "${{ needs.manual_capture.result }}",
        "FORWARD_RESULT": "${{ needs.manual_forward.result }}",
        "FORWARD_GATE": "${{ needs.manual_forward.outputs.forward_gate }}",
        "FORWARD_GATE_REASON": "${{ needs.manual_forward.outputs.forward_gate_reason }}",
        "OS_RESULT": "${{ needs.case_os_result.result }}",
        "EIGHT_P_RESULT": "${{ needs.case_8p_result.result }}",
        "SIXTEEN_P_RESULT": "${{ needs.case_16p_result.result }}",
        "LITE_GITCODE_MANUAL_PHASE": "aggregate",
    }
    header += _step(
        script,
        step_id="aggregate_manual_forward",
        step_name="Aggregate manual forward",
        environment=aggregate_environment,
    )
    return header, capture_script_sha256


if __name__ == "__main__":
    content, digest = render()
    OUTPUT.write_text(content)
    print("capture_bootstrap_script_sha256=" + digest)
