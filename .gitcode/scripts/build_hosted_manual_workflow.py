def scripts():
    source = TEMPLATE.read_text()
    if source.count("__SDK_SHA__") != 1 or source.count("__SDK_ARCHIVE_SHA256__") != 1:
        raise ValueError("SDK_BOOTSTRAP_PIN_PLACEHOLDER_INVALID")
    source = source.replace("__SDK_SHA__", SDK_SHA).replace("__SDK_ARCHIVE_SHA256__", SDK_ARCHIVE_SHA256)
    source = source.replace("__EXPECTED_FILES__", repr(SDK_FILES))
    command = "python3 -I -B - <<'PY'\n" + source.rstrip("\n") + "\nPY\n"
    return command, hashlib.sha256(command.encode()).hexdigest()


def _step(script, *, step_id, step_name, environment):
    lines = [
        "          - id: " + step_id,
        "            name: " + step_name,
        "            shell: bash",
        "            working-directory: '.'",
        "            env:",
    ]
    for key, value in environment.items():
        lines.append("              " + key + ": " + value)
    lines.append("            run: |")
    lines.extend("              " + line if line else "" for line in script.splitlines())
    return "\n".join(lines) + "\n"


