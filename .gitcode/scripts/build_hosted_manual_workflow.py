"""Generate reviewed self-contained manual control steps without runtime checkout."""

import ast
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / ".gitcode/scripts"
OUTPUT = ROOT / ".gitcode/workflows/torchtitan_forward_manual.yml"


def inline_source(name):
    source = (SCRIPTS / name).read_text()
    lines = source.splitlines(keepends=True)
    remove = set()
    for node in ast.parse(source).body:
        if isinstance(node, ast.ImportFrom) and node.module == "hosted_manual_common":
            remove.update(range(node.lineno - 1, node.end_lineno))
    return "".join(line for index, line in enumerate(lines) if index not in remove)


def scripts():
    common = (SCRIPTS / "hosted_manual_common.py").read_text()
    capture = "python3 -I -B - <<'PY'\n" + common + "\n" + inline_source("hosted_manual_capture.py") + "\nPY\n"
    digest = hashlib.sha256(capture.encode()).hexdigest()
    dispatch = (
        "python3 -I -B - <<'PY'\n"
        + common
        + "\n"
        + inline_source("hosted_manual_dispatch.py").replace("__CAPTURE_SCRIPT_SHA256__", digest)
        + "\nPY\n"
    )
    return capture, dispatch, digest


def render():
    capture, dispatch, digest = scripts()
    d = chr(36)
    header = """# Generated by .gitcode/scripts/build_hosted_manual_workflow.py; review source and exact script digest.
# Manual current-observation only, NOT original PR provenance or official CANN acceptance.
name: TorchTitan Personal Manual Forward
on:
  workflow_dispatch:
    inputs:
      pr_number:
        description: Open personal-repository PR number
        type: number
        required: true
      test_case:
        description: worker_os_blue keeps the current OS-only route; os_8p_16p explicitly selects all three cases
        type: choice
        options: [worker_os_blue, os_8p_16p]
        default: worker_os_blue
permissions:
  action: read
  repository: read
  pr: read
  project: read
  issue: none
  note: none
stages:
  manual:
    name: Manual personal prevalidation
    jobs:
"""
    env = {
        "EVENT_NAME": "${{ atomgit.event_name }}",
        "RUN_ATTEMPT": "${{ atomgit.run_attempt }}",
        "REPOSITORY": "${{ atomgit.repository }}",
        "REPOSITORY_ID": "${{ atomgit.repository_id }}",
        "REF": "${{ atomgit.ref }}",
        "ACTOR": "${{ atomgit.actor }}",
        "CONTROL_SHA": "${{ vars.LITE_GITCODE_BRIDGE_SHA }}",
        "ATOMGIT_TOKEN": "${{ atomgit.token }}",
    }
    for key, name, script in (
        ("manual_capture", "Capture manual request", capture),
        ("manual_forward", "Dispatch and wait exact GitHub run", dispatch),
    ):
        header += "      " + key + ":\n        name: " + key + "\n"
        header += (
            "        if: ${{ atomgit.repository == 'depeng1994/torchtitan-npu' && "
            "atomgit.event_name == 'Manual' && atomgit.ref == 'refs/heads/master' }}\n"
        )
        if key == "manual_forward":
            header += (
                "        needs: [manual_capture]\n"
                "        outputs:\n"
                "          case_os_result: " + d + "{{ steps.manual_forward.outputs.case_os_result }}\n"
                "          case_8p_result: " + d + "{{ steps.manual_forward.outputs.case_8p_result }}\n"
                "          case_16p_result: " + d + "{{ steps.manual_forward.outputs.case_16p_result }}\n"
                "          forward_gate: " + d + "{{ steps.manual_forward.outputs.forward_gate }}\n"
                "          forward_gate_reason: " + d + "{{ steps.manual_forward.outputs.forward_gate_reason }}\n"
            )
        header += (
            "        runs-on: [ubuntu-latest, x64, small]\n        timeout-minutes: 20\n"
            "        steps:\n          - id: " + key + "\n            name: "
            + name
            + "\n            shell: bash\n            working-directory: '.'\n            env:\n"
        )
        values = dict(env)
        if key == "manual_capture":
            values.update(
                PR_NUMBER="${{ inputs.pr_number }}",
                TEST_CASE="${{ inputs.test_case }}",
            )
        else:
            values["LITE_ACTIONS_GITHUB_TOKEN"] = "${{ secrets.LITE_ACTIONS_GITHUB_TOKEN }}"
        for field, value in values.items():
            header += "              " + field + ": " + value + "\n"
        header += "            run: |\n" + "".join(
            ("              " + line if line else "") + "\n" for line in script.splitlines()
        )
    for case_id, case_name, label in (
        ("worker_os_blue", "case_os_result", "OS result"),
        ("dispatch_smoke_8p", "case_8p_result", "8P result"),
        ("dispatch_smoke_16p", "case_16p_result", "16P result"),
    ):
        header += "      " + case_name + ":\n        name: " + label + "\n"
        header += (
            "        if: ${{ always() && atomgit.repository == 'depeng1994/torchtitan-npu' && "
            "atomgit.event_name == 'Manual' && atomgit.ref == 'refs/heads/master' }}\n"
            "        needs: [manual_capture, manual_forward]\n"
            "        runs-on: [ubuntu-latest, x64, small]\n"
            "        timeout-minutes: 5\n"
            "        steps:\n          - name: Publish " + label + "\n"
            "            shell: bash\n            working-directory: '.'\n            env:\n"
        )
        output_name = {
            "worker_os_blue": "case_os_result",
            "dispatch_smoke_8p": "case_8p_result",
            "dispatch_smoke_16p": "case_16p_result",
        }[case_id]
        values = {
            "RESULT_CASE": case_id,
            "CASE_EVIDENCE": "${{ needs.manual_forward.outputs." + output_name + " }}",
            "CAPTURE_RESULT": "${{ needs.manual_capture.result }}",
            "CAPTURE_RUN_ID": "${{ atomgit.run_id }}",
            "CAPTURE_ATTEMPT": "${{ atomgit.run_attempt }}",
            "CONTROL_SHA": "${{ vars.LITE_GITCODE_BRIDGE_SHA }}",
        }
        for field, value in values.items():
            header += "              " + field + ": " + value + "\n"
        header += "            run: |\n" + "".join(
            ("              " + line if line else "") + "\n" for line in dispatch.splitlines()
        )
    d = chr(36)
    header += (
        '      aggregate_gate:\n'
        '        name: Aggregate Forward and authority gate\n'
        '        if: ' + d + "{{ always() && atomgit.repository == 'depeng1994/torchtitan-npu' && atomgit.event_name == 'Manual' && atomgit.ref == 'refs/heads/master' }}\n"
        '        needs: [manual_capture, manual_forward, case_os_result, case_8p_result, case_16p_result]\n'
        '        runs-on: [ubuntu-latest, x64, small]\n'
        '        timeout-minutes: 2\n'
        '        steps:\n'
        '          - name: Enforce case and aggregate outcome independently\n'
        '            shell: bash\n'
        "            working-directory: '.'\n"
        '            env:\n'
        '              CAPTURE_RESULT: ' + d + '{{ needs.manual_capture.result }}\n'
        '              FORWARD_RESULT: ' + d + '{{ needs.manual_forward.result }}\n'
        '              FORWARD_GATE: ' + d + '{{ needs.manual_forward.outputs.forward_gate }}\n'
        '              FORWARD_GATE_REASON: ' + d + '{{ needs.manual_forward.outputs.forward_gate_reason }}\n'
        '              OS_RESULT: ' + d + '{{ needs.case_os_result.result }}\n'
        '              EIGHT_P_RESULT: ' + d + '{{ needs.case_8p_result.result }}\n'
        '              SIXTEEN_P_RESULT: ' + d + '{{ needs.case_16p_result.result }}\n'
        '            run: |\n'
        '              if [[ "$CAPTURE_RESULT" != success ]]; then echo aggregate_status=FAIL reason=CAPTURE_FAILED; exit 1; fi\n'
        '              if [[ "$FORWARD_RESULT" != success ]]; then echo aggregate_status=FAIL reason=FORWARD_FAILED_OR_MISSING_OUTPUT; exit 1; fi\n'
        '              if [[ -z "$FORWARD_GATE_REASON" ]]; then echo aggregate_status=FAIL reason=FORWARD_GATE_MISSING_OR_INVALID; exit 1; fi\n'
        '              case "$FORWARD_GATE_REASON" in OK|SELECTED_CASE_FAILED|GITHUB_RUN_NOT_SUCCESS|PR_AUTHORITY_MISMATCH|PR_AUTHORITY_UNAVAILABLE|CONTROL_AUTHORITY_MISMATCH|CONTROL_AUTHORITY_UNAVAILABLE|CAPTURE_REVOKED) ;; *) echo aggregate_status=FAIL reason=FORWARD_GATE_REASON_INVALID; exit 1;; esac\n'
        '              if [[ "$FORWARD_GATE" == success && "$FORWARD_GATE_REASON" != OK ]]; then echo aggregate_status=FAIL reason=FORWARD_GATE_REASON_MISMATCH; exit 1; fi\n'
        '              if [[ "$FORWARD_GATE" != success ]]; then echo "aggregate_status=FAIL reason=$FORWARD_GATE_REASON"; exit 1; fi\n'
        '              if [[ "$OS_RESULT" != success ]]; then echo aggregate_status=FAIL reason=OS_CASE_DISPLAY_FAILED; exit 1; fi\n'
        '              if [[ "$EIGHT_P_RESULT" != success ]]; then echo aggregate_status=FAIL reason=8P_CASE_DISPLAY_FAILED; exit 1; fi\n'
        '              if [[ "$SIXTEEN_P_RESULT" != success ]]; then echo aggregate_status=FAIL reason=16P_CASE_DISPLAY_FAILED; exit 1; fi\n'
        '              echo aggregate_status=PASS historical_only=true current_authority=NOT_PROVIDED\n'
    )
    return header, digest


if __name__ == "__main__":
    content, digest = render()
    OUTPUT.write_text(content)
    print("capture_script_sha256=" + digest)
